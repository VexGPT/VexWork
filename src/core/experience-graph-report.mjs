// Experience Relationship Graph — human-readable navigation report.
//
// A generated Markdown projection over the graph and its derivations, so a person or fresh AI can
// read "what can the human do, what is proven, what is debt, what is still unknown" without
// opening JSON. It owns no truth: every line is regenerated from the artifacts it summarizes.
//
// Pure: returns text.

const compare = (left, right) => (left < right ? -1 : left > right ? 1 : 0);
const short = (ref) => ref.split('.').slice(1).join('.') || ref;
const table = (header, rows) => [
  `| ${header.join(' | ')} |`,
  `|${header.map(() => '---').join('|')}|`,
  ...rows.map((row) => `| ${row.map((cell) => String(cell).replace(/\|/g, '\\|')).join(' | ')} |`),
].join('\n');

export function renderExperienceReport({ graph, frontier, routes, perturbations, convergence, lawProof, board }) {
  const families = graph.nodes.filter((node) => node.role === 'FAMILY').map((node) => node.ref).sort(compare);
  const routeRows = families.map((family) => {
    const own = routes.routes.filter((route) => route.family === family);
    const cells = lawProof ? lawProof.cells.filter((cell) => cell.family === family) : [];
    const proven = cells.filter((cell) => cell.status === 'PASS' || cell.status === 'PASS_PARTIAL').length;
    return [
      family,
      own.length,
      own.filter((route) => route.status === 'CLEARED').length,
      own.filter((route) => route.status === 'FRONTIER_DEBT').length,
      frontier.debt.filter((row) => row.family === family).length,
      lawProof ? `${proven}/${cells.length}` : 'not run',
    ];
  });
  const edgeKinds = {};
  for (const edge of graph.edges) edgeKinds[edge.kind] = (edgeKinds[edge.kind] ?? 0) + 1;

  const cleared = routes.routes.filter((route) => route.status === 'CLEARED');
  const lines = [];
  lines.push('# VexLife-Prod Experience Relationship Graph — generated report');
  lines.push('');
  lines.push('`[VXG RealForever]` · generated by `scripts/build-experience-graph.mjs` · do not edit by hand');
  lines.push('');
  lines.push('~~~text');
  lines.push(`source       ${graph.source.repository} @ ${graph.source.commit}`);
  lines.push(`graph        ${graph.fingerprint}`);
  lines.push(`nodes/edges  ${graph.nodes.length} / ${graph.edges.length}   (VexBoard projection: ${board.nodes.length} nodes, ${board.relationships.length} relationships)`);
  lines.push(`edge kinds   ${Object.entries(edgeKinds).sort(([a], [b]) => compare(a, b)).map(([kind, count]) => `${kind} ${count}`).join(' · ')}`);
  lines.push(`routes       ${Object.entries(routes.counts).map(([status, count]) => `${status} ${count}`).join(' · ')}`);
  lines.push(`test cases   ${routes.cases.length} generated (manifest ${routes.manifestFingerprint.slice(0, 12)})`);
  if (lawProof) lines.push(`law proof    ${Object.entries(lawProof.caseCounts).map(([status, count]) => `${status} ${count}`).join(' · ')}   current=${lawProof.current}`);
  lines.push(`debt         ${frontier.debt.length} (${Object.entries(frontier.byClass).filter(([, count]) => count).map(([key, count]) => `${key} ${count}`).join(' · ')})`);
  lines.push(`perturbation ${Object.entries(perturbations.answers).map(([state, count]) => `${state} ${count}`).join(' · ')}`);
  lines.push('~~~');
  lines.push('');
  lines.push('## Families');
  lines.push('');
  lines.push(table(['Family', 'routes', 'CLEARED', 'FRONTIER_DEBT', 'debt rows', 'law cells proven'], routeRows));
  lines.push('');
  lines.push('## Cleared routes (every coordinate stably addressable)');
  lines.push('');
  for (const route of cleared) {
    lines.push(`### \`${route.routeRef}\``);
    lines.push('');
    lines.push('~~~text');
    lines.push(route.explanation);
    lines.push('~~~');
    lines.push('');
  }
  lines.push('## Journeys the graph joins across owners');
  lines.push('');
  lines.push(table(['journey', 'shape', 'status', 'feeding routes', 'missing'], routes.journeys.map((journey) => [
    `\`${journey.journeyRef}\``, journey.shape, journey.status, journey.feedingRoutes.length,
    journey.missing.map((row) => `${row.predicate} @ \`${row.coordinate}\``).join('; ') || '—',
  ])));
  lines.push('');
  lines.push('## Frontier debt — highest leverage first');
  lines.push('');
  lines.push(table(['debt', 'class', 'blocks routes', 'rightful repair coordinate'], convergence.queries.debtDependents.slice(0, 25).map((row) => {
    const debt = frontier.debt.find((entry) => entry.ref === row.debtRef);
    return [`\`${debt.kind}\``, `${debt.debtClass} ${debt.debtClassMeaning}`, row.dependentRoutes.length, `\`${debt.coordinate}\``];
  })));
  lines.push('');
  const unblocking = frontier.debt.filter((row) => !convergence.queries.debtDependents.some((entry) => entry.debtRef === row.ref));
  lines.push(`${unblocking.length} further debt rows block no derived route yet (for example unbound elements whose relationship the graph cannot see at all).`);
  lines.push('');
  lines.push('## Perturbation questions answered or still open');
  lines.push('');
  const shown = perturbations.questions.filter((row) => row.answerState !== 'EXPECTED_FROM_LAW' || row.consideration === 'CAPTURE_RACE' || row.consideration === 'STALE_OBSERVATION');
  lines.push(table(['consideration', 'question', 'answer', 'expected'], shown.filter((row) => ['STALE_OBSERVATION', 'CAPTURE_RACE', 'RETRY_IDEMPOTENCY'].includes(row.consideration) || row.answerState !== 'UNKNOWN').map((row) => [
    row.consideration, row.question, row.answerState, row.expected,
  ])));
  lines.push('');
  lines.push(`Not generated: ${Object.entries(perturbations.notGenerated).map(([name, reason]) => `${name} — ${reason}`).join('; ')}.`);
  lines.push('');
  lines.push('## Independent-truth joins and the Relay gate');
  lines.push('');
  lines.push(table(['join', 'classification', 'independent owners'], convergence.joins.map((join) => [`\`${join.consumer}\``, join.classification, join.independentOwners.map((owner) => `\`${owner}\``).join(', ')])));
  lines.push('');
  lines.push(table(['stage', 'candidate question', 'verdict', 'missing inputs'], convergence.gate.questions.map((row) => [row.stage, row.question, row.verdict, row.missingInputs.join(', ') || '—'])));
  lines.push('');
  if (lawProof && lawProof.failures.length) {
    lines.push('## Law-proof failures');
    lines.push('');
    for (const failure of lawProof.failures) lines.push(`- \`${short(failure.state)} × ${short(failure.control)}\` — ${failure.detail}`);
    lines.push('');
  }
  lines.push('<!-- [VXG RealForever][VEXWORK][VEXLIFE-PROD][E2E][EXPERIENCE-GRAPH][GENERATED-REPORT] -->');
  return `${lines.join('\n')}\n`;
}

