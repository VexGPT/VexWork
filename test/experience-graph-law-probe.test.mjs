function evidenceFor(graph, rows) {
  return lawEvidence({ graph, plan: plan(), rows, runner: { command: 'fixture' } });
}

test('law evidence passes when executed outcomes land inside the graph and fails when they do not', () => {
  const graph = fixtureGraph();
  const derivation = deriveRoutes(graph, deriveFrontier(graph));
  const row = (family, state, control, result, stateFixture = state, controlFixture = control) => ({ family, state, stateFixture, control, controlFixture, result });
  const rows = [
    row('VexLifeSightFamily', 'Ready', 'Engage', { admitted: null, effect: 'EngageScope' }),
    row('VexLifeSightFamily', 'Ready', 'Stop', 'REJECT'),
    row('VexLifeSightFamily', 'Held', 'Stop', { admitted: null, effect: 'StopScope' }, 'Held#1'),
    row('VexLifeSightFamily', 'Held', 'Stop', 'REJECT', 'Held#0'),
    row('VexLifeSightFamily', 'Engaged', 'Stop', { admitted: null, effect: 'StopScope' }),
    row('VexLifeSightFamily', 'Engaged', 'Engage', { admitted: null, effect: 'EngageScope' }),
    row('VexLifeDictationFamily', 'Ready', 'Start', { admitted: 'Requesting', effect: 'BeginDictation' }),
    row('VexLifeReviewFamily', 'Pending', 'Keep', { admitted: null, effect: 'Accept' }),
    row('VexLifeGatewayFamily', 'HostHeld', 'Cancel', { error: 'IllegalArgumentException: needs a reason' }),
  ];
  const proof = compareLawEvidence({ graph, derivation, evidence: evidenceFor(graph, rows) });
  assert.equal(proof.current, true);
  const status = (state, control) => proof.cells.find((cell) => cell.state === state && cell.control === control).status;
  assert.equal(status('VexLifeSightFamily.Ready', 'VexLifeSightFamily.Engage'), 'PASS');
  assert.equal(status('VexLifeSightFamily.Ready', 'VexLifeSightFamily.Stop'), 'PASS');
  assert.equal(status('VexLifeSightFamily.Held', 'VexLifeSightFamily.Stop'), 'PASS', 'both guard alternatives executed');
  assert.equal(status('VexLifeSightFamily.Engaged', 'VexLifeSightFamily.Engage'), 'FAIL', 'the graph says Engaged refuses Engage');
  assert.equal(status('VexLifeReviewFamily.Pending', 'VexLifeReviewFamily.Keep'), 'PASS_PARTIAL', 'the mismatching-ref guard was never exercised');
  assert.equal(status('VexLifeQuietFamily.Kept', 'VexLifeQuietFamily.Begin'), 'NOT_RUN');
  assert.match(proof.failures[0].detail, /graph does not allow/);
  assert.equal(proof.cases.find((row) => row.caseRef === 'case:VexLifeSightFamily.Ready:Engage:0').status, 'PASS');
  assert.equal(proof.cases.find((row) => row.caseRef.startsWith('case:VexLifeSpeechModelsFamily')).status, 'NOT_RUN');

  const oddGraph = fixtureGraph({
    families: [...fixtureLaws(), readFamilyLaw({ path: 'src/commonMain/kotlin/vexlife/odd/VexLifeOddFamily.kt', text: UNREADABLE })],
  });
  const oddDerivation = deriveRoutes(oddGraph, deriveFrontier(oddGraph));
  const odd = compareLawEvidence({
    graph: oddGraph,
    derivation: oddDerivation,
    evidence: evidenceFor(oddGraph, [row('VexLifeOddFamily', 'One', 'Wait', 'REJECT')]),
  });
  const unread = odd.cells.find((cell) => cell.state === 'VexLifeOddFamily.One' && cell.control === 'VexLifeOddFamily.Wait');
  assert.equal(unread.status, 'NOT_RUN', 'executed evidence does not turn unread graph law into a REJECT proof');
  assert.match(unread.detail, /graph extraction debt blocks semantic comparison/);

  const rejected = compareLawEvidence({ graph, derivation, evidence: evidenceFor(graph, [row('VexLifeQuietFamily', 'Quiet', 'End', { error: 'IllegalArgumentException: bad' })]) });
  assert.equal(rejected.cells.find((cell) => cell.state === 'VexLifeQuietFamily.Quiet' && cell.control === 'VexLifeQuietFamily.End').status, 'FIXTURE_REJECTED');

  const exhaustive = compareLawEvidence({ graph, derivation, evidence: evidenceFor(graph, [
    row('RuntimeAvailability', 'State.Unavailable', 'Control.Ensure', { admitted: null, effect: 'EnsureOwned' }, 'U', 'Ensure#0'),
    row('RuntimeAvailability', 'State.Unavailable', 'Control.Ensure', { admitted: null, effect: 'ObserveOwned' }, 'U', 'Ensure#1'),
  ]) });
  assert.equal(exhaustive.cells.find((cell) => cell.state === 'RuntimeAvailability.State.Unavailable').status, 'PASS', 'an exhaustive payload when never refuses');
});

test('law evidence is bound to the Family law it exercised, not to presentation or localization around it', () => {
  const graph = fixtureGraph();
  const derivation = deriveRoutes(graph, deriveFrontier(graph));
  const evidence = evidenceFor(graph, []);
  assert.equal(evidence.schemaVersion, LAW_EVIDENCE_SCHEMA);
  assert.match(evidence.probeSourceSha256, /^[0-9a-f]{64}$/);
  assert.equal(evidence.lawFingerprint, lawFingerprint(graph));
  assert.ok(evidence.plan.every((family) => family.states.every((state) => state.fixtures.every((label) => typeof label === 'string'))));
  assert.equal(compareLawEvidence({ graph, derivation, evidence: { ...evidence, lawFingerprint: '0'.repeat(64) } }).current, false);
  assert.equal(compareLawEvidence({ graph, derivation, evidence: { ...evidence, source: { ...evidence.source, commit: 'f'.repeat(40) } } }).current, false);
  // A presentation-only change (an element and its MANIFESTS row) leaves the law fingerprint and the proof current.
  const presentation = normalizeExperienceGraph({ ...graph, edges: graph.edges.filter((edge) => edge.kind !== 'MANIFESTS') });
  assert.notEqual(presentation.fingerprint, graph.fingerprint);
  assert.equal(lawFingerprint(presentation), lawFingerprint(graph));
  assert.equal(compareLawEvidence({ graph: presentation, derivation, evidence }).current, true);
  // Older evidence without a law fingerprint still binds to the whole graph.
  const { lawFingerprint: omitted, ...legacy } = evidence;
  void omitted;
  assert.equal(compareLawEvidence({ graph: presentation, derivation, evidence: legacy }).current, false);
  assert.throws(() => compareLawEvidence({ graph, derivation, evidence: { schemaVersion: 'x' } }), /law evidence schema mismatch/);
});
