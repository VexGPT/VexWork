import assert from 'node:assert/strict';
import test from 'node:test';

import { readFamilyLaw } from '../src/core/experience-graph-kotlin-family.mjs';
import { LAW_EVIDENCE_SCHEMA, compareLawEvidence, indexEnums, lawEvidence, planLawProbe } from '../src/core/experience-graph-law-probe.mjs';
import { deriveFrontier, deriveRoutes } from '../src/core/experience-graph-derivation.mjs';
import { lawFingerprint, normalizeExperienceGraph } from '../src/core/experience-graph.mjs';
import { fixtureGraph, fixtureLaws } from './fixtures/experience-graph/graph.mjs';
import { FAMILY_SOURCES, KIND_CONTRACT, UNREADABLE } from './fixtures/experience-graph/fixtures.mjs';

function plan() {
  const files = [...FAMILY_SOURCES, { path: 'src/commonMain/kotlin/vexlife/kind/VexLifeKindContract.kt', text: KIND_CONTRACT }];
  return planLawProbe({ laws: fixtureLaws(), enumIndex: indexEnums(files), sourceTexts: new Map(files.map((file) => [file.path, file.text])) });
}

test('external enums are indexed with their package-qualified owner chain', () => {
  const index = indexEnums([{ path: 'k.kt', text: KIND_CONTRACT }, { path: 'n.kt', text: 'package p\nenum class Loose { A, B }\n' }]);
  assert.deepEqual(index.get('CandidateClass'), { qualified: 'vexlife.kind.VexLifeKindContract.CandidateClass', entries: ['Preference', 'Fact'] });
  assert.deepEqual(index.get('VexLifeKindContract.CandidateClass').entries, ['Preference', 'Fact']);
  assert.equal(index.get('Loose').qualified, 'p.Loose');
});

test('fixtures come from Product law: variants, enum entries and constructor require(Regex(...)) patterns', () => {
  const probe = plan();
  const family = (name) => probe.families.find((row) => row.family === name);
  const sight = family('VexLifeSightFamily');
  assert.equal(sight.runnable, true);
  assert.equal(sight.instance, 'vexlife.sight.VexLifeSightFamily');
  assert.deepEqual(sight.states.find((row) => row.variant === 'Held').fixtures.map((fixture) => fixture.expr), [
    'vexlife.sight.VexLifeSightFamily.Held(reason = vexlife.sight.VexLifeSightFamily.HoldReason.RouteUnreachable)',
    'vexlife.sight.VexLifeSightFamily.Held(reason = vexlife.sight.VexLifeSightFamily.HoldReason.ScreenSafetyNotCurrent)',
  ]);
  const review = family('VexLifeReviewFamily');
  const keep = review.controls.find((row) => row.variant === 'Keep').fixtures.map((fixture) => fixture.expr);
  assert.equal(keep.length, 2, 'two distinct refs exercise the candidate-match guard both ways');
  for (const expr of keep) assert.match(expr, /CandidateRef\("review\.vexlife-prod\.memory\.[0-9a-f]{8}"\)/);
  assert.notEqual(keep[0], keep[1]);
  assert.match(review.states.find((row) => row.variant === 'Pending').fixtures[0].expr, /candidateClass = vexlife\.kind\.VexLifeKindContract\.CandidateClass\.Preference/);
  assert.equal(family('VexLifeGatewayFamily').instance, 'vexlife.gateway.VexLifeGatewayFamily.Semantics');
  assert.equal(family('VexLifeStockFamily').states[0].fixtures.length, 8, 'axis products are bounded');
  assert.equal(family('VexLifeRecallFamily').runnable, false);
  assert.equal(family('VexLifeRecallFamily').notRunnable, 'Family declares no Control');
  assert.ok(!probe.families.some((row) => row.family === 'VexLifeSpeechModelsFamily'), 'availability-only law has no resolve() to probe');

  const unconstructible = planLawProbe({
    laws: fixtureLaws().filter((law) => law.family === 'VexLifeReviewFamily'),
    enumIndex: new Map(),
    sourceTexts: new Map(FAMILY_SOURCES.map((file) => [file.path, file.text])),
  });
  assert.match(unconstructible.families[0].states.find((row) => row.variant === 'Pending').notFixturable, /no deterministic fixture for candidateClass/);
});

